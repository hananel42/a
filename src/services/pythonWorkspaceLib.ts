    '"""',
    'Tool execution helper module.',
    'Invokes authorized tools on behalf of the agent (e.g. read_file, write_file, search_wikipedia, etc.)',
    '"""',
    'import os',
    'import json',
    '',
    'import urllib.parse',
    'from .fs import fs',
    'from .agent import agent',
    '',
    'class ToolHelper:',
    '    def __init__(self, fs_client, agent_client):',
    '        self.fs = fs_client',
    '        self.agent = agent_client',
    '        perms_raw = os.environ.get("AGENT_PERMISSIONS", "")',
    '        self.permissions = json.loads(perms_raw) if perms_raw else None',
    '        self.agent_id = os.environ.get("AGENT_ID", "")',
    '',
    '    def _check_tool_permission(self, tool_name: str):',
    '        if not self.permissions:',
    '            return',
    '        allowed_tools = self.permissions.get("allowedTools", [])',
    '        if allowed_tools and tool_name not in allowed_tools:',
    '            raise PermissionError(f"Tool \'{tool_name}\' is not authorized for agent \'{self.agent_id}\'. Authorized tools: {allowed_tools}")',
    '',
    '    def execute_tool(self, tool_name: str, params: dict = None) -> dict:',
    '        if params is None:',
    '            params = {}',
    '        self._check_tool_permission(tool_name)',
    '        t = tool_name.lower()',
    '        if t == "search_wikipedia":',
    '            return {"result": self._search_wikipedia(params.get("query", ""), params.get("limit", 3))}',
    '        elif t == "read_file":',
    '            p = params.get("filePath") or params.get("path") or "."',
    '            return {"content": self.fs.read(p)}',
    '        elif t == "write_file":',
    '            p = params.get("filePath") or params.get("path")',
    '            c = params.get("content", "")',
    '            self.fs.write(p, c)',
    '            return {"status": "success", "path": p}',
    '        elif t == "list_dir":',
    '            p = params.get("path") or params.get("dirPath") or "."',
    '            return {"files": self.fs.list(p)}',
    '        elif t == "delete_file":',
    '            p = params.get("filePath") or params.get("path")',
    '            self.fs.delete(p)',
    '            return {"status": "deleted", "path": p}',
    '        elif t == "get_info":',
    '            p = params.get("filePath") or params.get("path") or "."',
    '            self.fs._check_permission(p, "read")',
    '            st = os.stat(p)',
    '            return {"path": p, "size": st.st_size, "is_file": os.path.isfile(p), "is_dir": os.path.isdir(p)}',
    '        elif t == "save_memory":',
    '            m = params.get("text") or params.get("memory") or ""',
    '            self.agent.save_memory(m)',
    '            return {"status": "memory_saved"}',
    '        else:',
    '            raise ValueError(f"Tool \'{tool_name}\' is not supported")',
    '',
    '    def _search_wikipedia(self, query: str, limit: int = 3) -> list:',
    '        import js',
    '        encoded_query = urllib.parse.quote(query)',
    '        url = f"https://en.wikipedia.org/w/api.php?action=query&list=search&srsearch={encoded_query}&utf8=&format=json&origin=*"',
    '        xhr = js.XMLHttpRequest.new()',
    '        xhr.open("GET", url, False)',
    '        try:',
    '            xhr.send()',
    '            if xhr.status >= 200 and xhr.status < 300:',
    '                data = json.loads(xhr.responseText)',
    '                results = data.get("query", {}).get("search", [])[:limit]',
    '                clean_results = []',
    '                for r in results:',
    '                    snippet = r.get("snippet", "").replace(\'<span class="searchmatch">\', "").replace("</span>", "")',
    '                    clean_results.append({"title": r.get("title"), "snippet": snippet, "pageid": r.get("pageid")})',
    '                return clean_results',
    '            else:',
    '                return [{"error": f"Wikipedia search failed: HTTP {xhr.status}"}]',
    '        except Exception as e:',
    '            return [{"error": f"Wikipedia search failed: {str(e)}"}]',
    '',
    'tools = ToolHelper(fs, agent)',
    ''
