    '"""',
    'Filesystem access module with agent permission enforcement.',
    '"""',
    'import os',
    'import json',
    'import shutil',
    '',
    'class Filesystem:',
    '    def __init__(self):',
    '        perms_raw = os.environ.get("AGENT_PERMISSIONS", "")',
    '        self.permissions = json.loads(perms_raw) if perms_raw else None',
    '        self.agent_id = os.environ.get("AGENT_ID", "")',
    '',
    '    def _normalize_path(self, path_str: str) -> str:',
    '        clean = str(path_str).replace("\\\\", "/").strip()',
    '        if clean.startswith("./"):',
    '            clean = clean[2:]',
    '        return clean.lstrip("/")',
    '',
    '    def _check_permission(self, path_str: str, mode: str = "read"):',
    '        if not self.permissions:',
    '            return',
    '        clean_path = self._normalize_path(path_str).lower()',
    '        allow_agent_folder = self.permissions.get("allowAgentFolderAccess", False)',
    '        if clean_path.startswith(".agents") and not allow_agent_folder:',
    '            if self.agent_id:',
    '                allowed_prefix = f".agents/{self.agent_id.lower()}"',
    '                if not (clean_path == allowed_prefix or clean_path.startswith(allowed_prefix + "/")):',
    '                    raise PermissionError(f"Access denied: Path \'{path_str}\' is inside protected .agents directory.")',
    '            else:',
    '                raise PermissionError(f"Access denied: Path \'{path_str}\' is inside protected .agents directory.")',
    '        allowed_list = self.permissions.get("allowedReadPaths" if mode == "read" else "allowedWritePaths")',
    '        if not allowed_list:',
    '            allowed_list = self.permissions.get("allowedPaths", ["/"])',
    '        if not allowed_list or "/" in allowed_list or "" in allowed_list:',
    '            return',
    '        is_ok = False',
    '        for prefix in allowed_list:',
    '            clean_prefix = self._normalize_path(prefix).lower()',
    '            if not clean_prefix or clean_prefix == "/" or clean_prefix == ".":',
    '                is_ok = True',
    '                break',
    '            if clean_path == clean_prefix or clean_path.startswith(clean_prefix + "/"):',
    '                is_ok = True',
    '                break',
    '        if not is_ok:',
    '            raise PermissionError(f"Permission Error ({mode}): Path \'{path_str}\' is restricted for agent \'{self.agent_id}\'.")',
    '',
    '    def read(self, path: str, encoding: str = "utf-8") -> str:',
    '        self._check_permission(path, "read")',
    '        with open(path, "r", encoding=encoding) as f:',
    '            return f.read()',
    '',
    '    def write(self, path: str, content: str, encoding: str = "utf-8"):',
    '        self._check_permission(path, "write")',
    '        os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)',
    '        with open(path, "w", encoding=encoding) as f:',
    '            f.write(content)',
    '',
    '    def append(self, path: str, content: str, encoding: str = "utf-8"):',
    '        self._check_permission(path, "write")',
    '        os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)',
    '        with open(path, "a", encoding=encoding) as f:',
    '            f.write(content)',
    '',
    '    def list(self, path: str = ".") -> list:',
    '        self._check_permission(path, "read")',
    '        return os.listdir(path)',
    '',
    '    def exists(self, path: str) -> bool:',
    '        return os.path.exists(path)',
    '',
    '    def is_file(self, path: str) -> bool:',
    '        return os.path.isfile(path)',
    '',
    '    def is_dir(self, path: str) -> bool:',
    '        return os.path.isdir(path)',
    '',
